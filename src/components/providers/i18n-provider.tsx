const dictionaries: Record<Language, Record<Key, string>> = { en, fr, es, pt };
const Context = createContext({
  locale: "en" as Language,
  setLocale: (() => undefined) as (next: Language) => void,
  t: (key: Key) => en[key] as string,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Language>("en");
  const value = useMemo(
    () => ({
      locale,
      setLocale(next: Language) {
        setLocaleState(next);
        document.documentElement.lang = next;
        localStorage.setItem("10trials-language", next);
      },
      t(key: Key) {
        return dictionaries[locale][key];
      },
    }),
    [locale],
  );
  return <Context.Provider value={value}>{children}</Context.Provider>;
}
export function useI18n() {
  return useContext(Context);
}
